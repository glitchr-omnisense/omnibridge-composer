<?php

namespace Omnibridge\Composer\Stub;

/**
 * The generic generator: mirrors the classes of a source namespace under a
 * target namespace, one stub per class -
 *
 *     namespace App\Entity;
 *     if (!class_exists('\App\Entity\User')) {
 *         class User extends \Base\Entity\User {}
 *     }
 *
 * - for a package that, at run time, makes each Target\X an alias of
 * Source\X unless the application defines Target\X itself (omnibase's
 * Base\ and App\). The stub tells an IDE what the alias gives; the guard
 * keeps it harmless should anything ever include it.
 *
 * A class gets a stub when it is a plain class (not abstract, final or
 * readonly; not an interface, a trait or an enum) and the application has no
 * file of the same relative path in getApplicationDirectory().
 */
abstract class AbstractStub implements StubInterface
{
    /** The namespace mirrored, such as Base\Entity. */
    abstract protected function getSourceNamespace(): string;

    /** The directory of the source namespace, absolute. */
    abstract protected function getSourceDirectory(StubContext $context): string;

    /** The namespace of the stubs, such as App\Entity. */
    abstract protected function getTargetNamespace(): string;

    /** Where the application's own classes of the target namespace live (a class there gets no stub); null for none. */
    protected function getApplicationDirectory(StubContext $context): ?string
    {
        return null;
    }

    public function generate(StubContext $context): iterable
    {
        $sourceDir = rtrim($this->getSourceDirectory($context), '/');
        if (!is_dir($sourceDir)) {
            return [];
        }

        $applicationDir = $this->getApplicationDirectory($context);
        $source = trim($this->getSourceNamespace(), '\\');
        $target = trim($this->getTargetNamespace(), '\\');

        $files = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($sourceDir, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if (!$file->isFile() || 'php' !== $file->getExtension()) {
                continue;
            }

            $relative = substr($file->getPathname(), strlen($sourceDir) + 1);
            if (null !== $applicationDir && file_exists(rtrim($applicationDir, '/').'/'.$relative)) {
                continue;
            }

            $declaration = self::declaration((string) file_get_contents($file->getPathname()));
            if (null === $declaration || 'class' !== $declaration['kind'] || $declaration['modifiers']) {
                continue;
            }

            $namespace = $declaration['namespace'];
            if ($namespace !== $source && !str_starts_with($namespace, $source.'\\')) {
                continue;
            }

            $files[$relative] = $this->render($target.substr($namespace, strlen($source)), $declaration['name'], $namespace.'\\'.$declaration['name']);
        }

        ksort($files, SORT_STRING);

        return $files;
    }

    /** The stub of $class under $namespace. */
    protected function render(string $namespace, string $name, string $class): string
    {
        return "<?php\n\n"
            ."namespace $namespace;\n\n"
            ."/**\n"
            ." * Generated by omnibridge/composer (".static::class.") for an IDE and static\n"
            ." * analysis: at run time $namespace\\$name is $class unless the application\n"
            ." * defines it. Never autoloaded; rewritten at every composer dump-autoload.\n"
            ." */\n\n"
            ."if (!class_exists('\\$namespace\\$name')) {\n"
            ."    class $name extends \\$class {}\n"
            ."}\n";
    }

    /**
     * The first class-like declaration of a file: its namespace, name, kind
     * and modifiers, from PHP's tokenizer.
     *
     * @return array{namespace: string, name: string, kind: string, modifiers: string[]}|null
     */
    public static function declaration(string $code): ?array
    {
        $tokens = array_values(array_filter(\PhpToken::tokenize($code), static fn (\PhpToken $t) => !$t->isIgnorable()));
        $namespace = '';
        $modifiers = [];
        foreach ($tokens as $i => $token) {
            if ($token->is(T_NAMESPACE) && isset($tokens[$i + 1]) && $tokens[$i + 1]->is([T_NAME_QUALIFIED, T_STRING])) {
                $namespace = $tokens[$i + 1]->text;
                continue;
            }
            if ($token->is([T_ABSTRACT, T_FINAL, T_READONLY])) {
                $modifiers[] = strtolower($token->text);
                continue;
            }
            if ($token->is([T_CLASS, T_INTERFACE, T_TRAIT, T_ENUM])) {
                $previous = $tokens[$i - 1] ?? null;
                if (null !== $previous && $previous->is([T_DOUBLE_COLON, T_NEW])) {
                    $modifiers = [];
                    continue;
                }
                $name = $tokens[$i + 1] ?? null;
                if (null === $name || !$name->is(T_STRING)) {
                    continue;
                }

                return ['namespace' => $namespace, 'name' => $name->text, 'kind' => strtolower($token->text), 'modifiers' => $modifiers];
            }
            if ($token->is([';', '{', '}'])) {
                $modifiers = [];
            }
        }

        return null;
    }
}
